public class bitman {
    public static void main(String[] args) {
        System.out.println(5&6);//AND operation
        System.out.println(5|6);//OR operation
        System.out.println(5^6);//XOR operation
        System.out.println(~5);//ones compliment
        System.out.println(5<<2);//left shift
        System.out.println(6>>1);//right shift
    }
    
}
